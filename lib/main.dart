# YH Online Business — Flutter starter

This is a starter UI project for the YH Online Business Android/iOS marketplace.

## Included
- Green/white brand theme
- Home, Shop, Income Zone, Seller and Account tabs
- Sample category and product cards
- Placeholder sections for marketplace and earning features

## Run
1. Install Flutter SDK and Android Studio (and Xcode on macOS for iOS builds).
2. In this folder run: `flutter pub get`
3. Run on a connected device/emulator: `flutter run`

## Important
This is a UI starter, not a production marketplace. It does not yet include authentication,
database, seller approval, inventory, order processing, payment gateway, withdrawals,
ad network integration, or admin dashboard. These require backend services, merchant
approvals, security rules, testing and legal/compliance review before launch.

